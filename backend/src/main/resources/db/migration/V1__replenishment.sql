CREATE TABLE location (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('WAREHOUSE','STORE')),
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE app_user (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login_id text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE user_role (
  user_id bigint REFERENCES app_user,
  role_code text CHECK (role_code IN ('STORE','APPROVER')),
  PRIMARY KEY (user_id, role_code)
);
CREATE TABLE user_location (
  user_id bigint REFERENCES app_user,
  location_id bigint REFERENCES location,
  active boolean NOT NULL DEFAULT true,
  PRIMARY KEY (user_id, location_id)
);
CREATE TABLE product (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE product_variant (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES product,
  sku_code text NOT NULL UNIQUE,
  color_code text NOT NULL,
  size_code text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  UNIQUE(product_id,color_code,size_code)
);
CREATE TABLE replenishment_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_location_id bigint NOT NULL REFERENCES location,
  destination_location_id bigint NOT NULL REFERENCES location,
  requested_by bigint NOT NULL REFERENCES app_user,
  allow_partial boolean NOT NULL,
  desired_receipt_date date NOT NULL,
  status text NOT NULL CHECK(status IN ('SUBMITTED','FULFILLING','CANCELLED')),
  version bigint NOT NULL DEFAULT 0 CHECK(version >= 0),
  submitted_at timestamptz NOT NULL DEFAULT now(),
  CHECK(source_location_id <> destination_location_id)
);
CREATE INDEX ON replenishment_request(destination_location_id, submitted_at DESC, id DESC);
CREATE INDEX ON replenishment_request(source_location_id, submitted_at DESC, id DESC);
CREATE TABLE replenishment_request_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES replenishment_request,
  variant_id bigint NOT NULL REFERENCES product_variant,
  requested_qty integer NOT NULL CHECK(requested_qty > 0),
  open_qty integer NOT NULL CHECK(open_qty >= 0),
  reserved_qty integer NOT NULL DEFAULT 0 CHECK(reserved_qty >= 0),
  shipped_qty integer NOT NULL DEFAULT 0 CHECK(shipped_qty >= 0),
  closed_qty integer NOT NULL DEFAULT 0 CHECK(closed_qty >= 0),
  CHECK(requested_qty::bigint = open_qty::bigint + reserved_qty + shipped_qty + closed_qty),
  UNIQUE(request_id, variant_id)
);
CREATE TABLE replenishment_approval (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES replenishment_request,
  decided_by bigint NOT NULL REFERENCES app_user,
  reason text,
  decided_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE replenishment_approval_item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  approval_id bigint NOT NULL REFERENCES replenishment_approval,
  request_item_id bigint NOT NULL REFERENCES replenishment_request_item,
  approved_qty integer NOT NULL CHECK(approved_qty >= 0),
  UNIQUE(approval_id, request_item_id)
);
CREATE TABLE inventory_balance (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id bigint NOT NULL REFERENCES location,
  variant_id bigint NOT NULL REFERENCES product_variant,
  normal_qty integer NOT NULL CHECK(normal_qty >= 0),
  held_qty integer NOT NULL DEFAULT 0 CHECK(held_qty >= 0),
  reserved_qty integer NOT NULL DEFAULT 0 CHECK(reserved_qty BETWEEN 0 AND normal_qty),
  UNIQUE(location_id, variant_id)
);
CREATE TABLE inventory_reservation (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  approval_item_id bigint NOT NULL UNIQUE REFERENCES replenishment_approval_item,
  balance_id bigint NOT NULL REFERENCES inventory_balance,
  initial_qty integer NOT NULL CHECK(initial_qty > 0),
  released_qty integer NOT NULL DEFAULT 0 CHECK(released_qty BETWEEN 0 AND initial_qty)
);
CREATE TABLE inventory_movement (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id bigint NOT NULL REFERENCES inventory_reservation,
  actor_id bigint NOT NULL REFERENCES app_user,
  reserved_delta integer NOT NULL CHECK(reserved_delta <> 0),
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE request_status_history (
  request_id bigint REFERENCES replenishment_request,
  resulting_version bigint,
  from_status text,
  to_status text NOT NULL,
  actor_id bigint NOT NULL REFERENCES app_user,
  reason text,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(request_id,resulting_version)
);
CREATE TABLE request_line_closure (
  request_item_id bigint PRIMARY KEY REFERENCES replenishment_request_item,
  qty integer NOT NULL CHECK(qty > 0),
  actor_id bigint NOT NULL REFERENCES app_user,
  reason text NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE submission_result (
  actor_id bigint REFERENCES app_user,
  idempotency_key text,
  request_hash text NOT NULL,
  request_id bigint REFERENCES replenishment_request,
  response jsonb,
  PRIMARY KEY(actor_id,idempotency_key)
);
CREATE TABLE command_result (
  command_type text,
  request_id bigint REFERENCES replenishment_request,
  actor_id bigint REFERENCES app_user,
  idempotency_key text,
  request_hash text NOT NULL,
  response jsonb NOT NULL,
  PRIMARY KEY(command_type,request_id,actor_id,idempotency_key)
);
